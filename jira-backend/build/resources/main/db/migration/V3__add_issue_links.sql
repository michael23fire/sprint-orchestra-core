CREATE TABLE issue_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_issue_id BIGINT NOT NULL,
    target_issue_id BIGINT NOT NULL,
    link_type VARCHAR(30) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_issue_links_source FOREIGN KEY (source_issue_id) REFERENCES issues (id),
    CONSTRAINT fk_issue_links_target FOREIGN KEY (target_issue_id) REFERENCES issues (id),
    CONSTRAINT uk_issue_links_source_target_type UNIQUE (source_issue_id, target_issue_id, link_type)
);

CREATE INDEX idx_issue_links_source ON issue_links (source_issue_id);
CREATE INDEX idx_issue_links_target ON issue_links (target_issue_id);
