CREATE TABLE issue_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL,
    uploader_id BIGINT,
    original_filename VARCHAR(255) NOT NULL,
    storage_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(120),
    size_bytes BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_issue_attachments_issue FOREIGN KEY (issue_id) REFERENCES issues (id),
    CONSTRAINT fk_issue_attachments_uploader FOREIGN KEY (uploader_id) REFERENCES users (id),
    CONSTRAINT uk_issue_attachments_storage_filename UNIQUE (storage_filename)
);

CREATE INDEX idx_issue_attachments_issue ON issue_attachments (issue_id);
