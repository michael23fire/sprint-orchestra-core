CREATE TABLE issue_code_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL,
    creator_id BIGINT,
    -- Raw URL the user pasted. Kept verbatim so we can always re-render it.
    url VARCHAR(1024) NOT NULL,
    -- One of: pull_request | commit | branch | repo | other
    kind VARCHAR(30) NOT NULL,
    provider VARCHAR(30) NOT NULL DEFAULT 'github',
    owner VARCHAR(120),
    repo VARCHAR(200),
    -- For PRs: PR number. For commits: short SHA. For branches: branch name.
    ref_id VARCHAR(200),
    title VARCHAR(500),
    state VARCHAR(40),
    author_login VARCHAR(120),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_issue_code_links_issue FOREIGN KEY (issue_id) REFERENCES issues (id),
    CONSTRAINT fk_issue_code_links_creator FOREIGN KEY (creator_id) REFERENCES users (id),
    CONSTRAINT uk_issue_code_links_issue_url UNIQUE (issue_id, url)
);

CREATE INDEX idx_issue_code_links_issue ON issue_code_links (issue_id);
CREATE INDEX idx_issue_code_links_kind ON issue_code_links (kind);
