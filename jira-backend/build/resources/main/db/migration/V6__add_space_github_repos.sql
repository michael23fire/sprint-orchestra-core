CREATE TABLE space_github_repos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id BIGINT NOT NULL,
    owner VARCHAR(120) NOT NULL,
    repo VARCHAR(200) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_scanned_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_space_github_repos_space FOREIGN KEY (space_id) REFERENCES spaces (id),
    CONSTRAINT uk_space_github_repos UNIQUE (space_id, owner, repo)
);

CREATE INDEX idx_space_github_repos_space ON space_github_repos (space_id);
